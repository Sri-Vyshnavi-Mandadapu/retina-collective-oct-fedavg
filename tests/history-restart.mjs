import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
await mkdir('artifacts',{recursive:true});
const profile=await mkdtemp(resolve('artifacts/history-restart-'));
const url='https://merry-otter-714f0d.netlify.app';
const key='retina-collective-history-v1';
let context;
try {
 context=await chromium.launchPersistentContext(profile,{channel:'chrome',headless:true});
 let page=await context.newPage();
 await page.goto(url);
 await page.waitForFunction(()=>document.getElementById('status-text').textContent.includes('round 16'));
 assert.equal(await page.locator('#remember').isChecked(),true,'Saving history should be enabled by default');
 await page.locator('#scan-name').fill('Restart persistence verification');
 await page.locator('#file-input').setInputFiles('tests/fixtures/pattern-0.png');
 await page.locator('#oct-confirm').check();
 await page.locator('#analyze-button').click();
 await page.waitForFunction(key=>JSON.parse(localStorage.getItem(key)||'[]').length===1,key,{timeout:240000});
 const before=await page.evaluate(key=>JSON.parse(localStorage.getItem(key))[0],key);
 assert.ok(before.thumbnail);
 assert.ok((await page.locator('#condition-description').textContent()).length>50);
 await page.reload();
 await page.locator('[data-route="history"]').click();
 assert.equal(await page.locator('.history-item').count(),1);
 await context.close();context=null;
 context=await chromium.launchPersistentContext(profile,{channel:'chrome',headless:true});
 page=await context.newPage();
 await page.goto(url+'/#history');
 await page.locator('.history-item').waitFor();
 const after=await page.evaluate(key=>JSON.parse(localStorage.getItem(key))[0],key);
 assert.deepEqual(after,before,'Browser restart must retain the entire report and thumbnail');
 assert.match(await page.locator('.history-item').textContent(),/Restart persistence verification/);
 assert.match(await page.locator('.history-item').textContent(),/About this category:/);
 await page.locator('.history-item .history-actions button').first().click();
 assert.equal(await page.locator('#prediction-label').textContent(),before.prediction);
 assert.ok((await page.locator('#condition-description').textContent()).length>50);
 const report={url,passed:true,verified:['history enabled by default','actual model inference','page reload','complete browser process shutdown and relaunch','same report, scores, model, thumbnail and timestamp restored','saved report reopens with condition description'],scope:'Same normal browser profile and origin; private browsing and cleared site data are excluded.'};
 await writeFile('artifacts/history-restart-verification.json',JSON.stringify(report,null,2));
 console.log('PASS: real scan history survives page reload and full browser restart, including scores, thumbnail and condition description.');
} finally {await context?.close();}
